const assert=require('node:assert/strict');
const m=require('./toolkit-math.js');
const near=(a,b,tol=1e-6)=>assert.ok(Math.abs(a-b)<tol,`${a} ≠ ${b}`);
const base={n:40,confidence:95,power:80,rate:50,sd:1.1};
near(m.reverse('rate',base).value,15.4948758076);
near(m.reverse('mean',base).value,.3408872678);
near(m.reverse('independent',base).value,.9745329383);
assert.equal(m.reverse('independent',{...base,n:41}).groupA,20);
assert.equal(m.reverse('independent',{...base,n:41}).groupB,21);
assert.ok(m.reverse('rate',{...base,n:80}).value<m.reverse('rate',base).value);
const w=m.wilson(82,100);
near(w.low,.7333264161);near(w.high,.8829977450);
near(m.wilson(0,10).low,0);near(m.wilson(10,10).high,1);
assert.ok(m.wilson(82,100,95,true).low>w.low);
const g={n:100,positive:82,goal:80,confidence:95,direction:'two'};
assert.equal(m.goal('rate',g).status,'uncertain');
assert.equal(m.goal('rate',{...g,positive:95}).status,'above');
assert.equal(m.goal('rate',{...g,positive:60}).status,'below');
assert.equal(m.goal('rate',{...g,positive:60,direction:'above'}).status,'uncertain');
assert.equal(m.goal('mean',{n:100,mean:75,sd:20,goal:68,confidence:95,direction:'two'}).status,'above');
const v={metric:'rate',margin:10,rate:50,confidence:95,loss:10,overlap:'exclusive'};
const rows=[{share:60},{share:40}];
const s=m.segments(rows,v);
assert.equal(s.required,97);assert.equal(s.recruit,108);assert.equal(s.minimum,194);assert.equal(s.recruitMaximum,216);assert.equal(s.natural,243);
const o=m.segments(rows,{...v,overlap:'overlap'});
assert.equal(o.minimum,97);assert.equal(o.maximum,194);
for(const bad of [NaN,0,-1,1.5])assert.throws(()=>m.reverse('rate',{...base,n:bad}));
assert.throws(()=>m.wilson(101,100));assert.throws(()=>m.wilson(2.5,10));
assert.throws(()=>m.segments([{share:30},{share:30}],v));
assert.throws(()=>m.segments([],v));assert.throws(()=>m.segments([{share:0}],v));
console.log('Toolkit numerical references, goal classifications, segment accounting, endpoints, and validation passed.');
