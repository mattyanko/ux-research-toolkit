const assert=require('node:assert/strict');
const {calculate:c,z}=require('./calculator.js');
const base={loss:0,confidence:95,power:80};
assert.ok(Math.abs(z(.975)-1.95996398454)<1e-7);
assert.ok(Math.abs(z(.8)-.84162123357)<1e-7);
assert.ok(Math.abs(z(.01)+2.32634787404)<1e-7);
assert.equal(c('discovery',{...base,occurrence:15,target:80}).total,10);
assert.equal(c('discovery',{...base,occurrence:25,target:85}).total,7);
assert.equal(c('discovery',{...base,occurrence:20,target:85}).total,9);
assert.equal(c('rate',{...base,rate:50,margin:5}).total,385);
assert.equal(c('rate',{...base,rate:50,margin:5,population:2500}).total,334);
assert.equal(c('rate',{...base,rate:50,margin:5,population:2500,loss:10}).recruit,372);
assert.equal(c('rate',{...base,rate:50,margin:5,population:2500}).uncorrectedN,385);
assert.equal(c('rate',{...base,rate:50,margin:5,population:100}).total,80);
assert.equal(c('rate',{...base,rate:50,margin:5,population:2}).total,2);
for(const population of [0,1,2.5,NaN,Infinity])assert.throws(()=>c('rate',{...base,rate:50,margin:5,population}));
assert.equal(c('rate',{...base,rate:95,margin:5}).total,73);
assert.equal(c('mean',{...base,sd:20,margin:5}).total,62);
assert.equal(c('independent',{...base,sd:20,difference:8}).n,99);
assert.equal(c('paired',{...base,sd:15,difference:8}).n,28);
assert.equal(c('rates',{...base,rateA:70,rateB:90}).n,62);
let a=c('independent',{...base,sd:20,difference:8,loss:10});
assert.equal(a.recruit,220);
assert.equal(a.total,198);
assert.ok(c('rate',{...base,rate:50,margin:3}).total>385);
assert.ok(c('independent',{...base,sd:20,difference:8,power:90}).total>198);
for(const loss of [-1,100,NaN])assert.throws(()=>c('mean',{...base,sd:20,margin:5,loss}));
assert.throws(()=>c('rates',{...base,rateA:70,rateB:70}));
assert.throws(()=>c('mean',{...base,sd:0,margin:5}));
assert.throws(()=>c('rate',{...base,rate:100,margin:5}));
assert.throws(()=>c('paired',{...base,sd:15,difference:NaN}));
// New benchmark cases independently calculated with Python NormalDist.
const goal={...base,benchmark:80,expected:90};
assert.equal(c('goalRate',goal).n,83);
assert.equal(c('goalRate',goal).tails,1);
assert.equal(c('benchmarkRate',goal).n,108);
assert.equal(c('benchmarkRate',{...goal,direction:'greater'}).n,83);
assert.equal(c('benchmarkRate',{...base,benchmark:20,expected:10,direction:'less'}).n,83);
assert.equal(c('benchmarkMean',{...base,benchmark:68,expected:75,sd:20}).n,65);
assert.equal(c('benchmarkMean',{...base,benchmark:68,expected:75,sd:20,direction:'greater'}).n,51);
assert.equal(c('benchmarkMean',{...base,benchmark:-5,expected:2,sd:20}).n,65);
assert.throws(()=>c('goalRate',{...goal,expected:80}));
assert.throws(()=>c('goalRate',{...goal,expected:70}));
assert.throws(()=>c('benchmarkMean',{...base,benchmark:68,expected:65,sd:20,direction:'greater'}));
assert.throws(()=>c('rates',{...base,rateA:90,rateB:70,direction:'greater'}));
for(const type of ['independent','paired','rates']){
 const v={...base,sd:20,difference:8,rateA:70,rateB:90};
 assert.ok(c(type,{...v,direction:'greater'}).n<c(type,v).n);
}
assert.throws(()=>c('goalRate',{...goal,correction:'bonferroni',familyCount:5}));
assert.equal(c('mean',{...base,sd:1.1,margin:.2}).n,117);
assert.equal(c('independent',{...base,sd:1.1,difference:.3}).n,212);
console.log('Unadjusted numerical references, five-point examples, directional tests, and input validation passed.');
const ordinal={...base,distributionA:[10,15,30,30,15],distributionB:[5,10,20,35,30]};
const mw=c('ordinal',ordinal);
assert.equal(mw.groups,2);
assert.equal(mw.n,82);
assert.equal(c('ordinal',{...ordinal,distributionA:ordinal.distributionB,distributionB:ordinal.distributionA}).n,mw.n);
assert.equal(c('ordinal',{...ordinal,distributionA:[...ordinal.distributionA,0,0],distributionB:[...ordinal.distributionB,0,0]}).n,mw.n);
assert.ok(c('ordinal',{...ordinal,power:90}).n>mw.n);
assert.throws(()=>c('ordinal',{...ordinal,distributionB:ordinal.distributionA}));
assert.throws(()=>c('ordinal',{...ordinal,distributionA:[10,10,10,10,10]}));
assert.throws(()=>c('ordinal',{...ordinal,distributionA:[-10,35,30,30,15]}));
assert.throws(()=>c('ordinal',{...ordinal,direction:'greater'}));
assert.throws(()=>c('ordinal',{...ordinal,distributionA:[50,0,0,0,50],distributionB:[0,0,100,0,0]}));
assert.equal(c('ordinal',{...ordinal,loss:10}).recruit,2*Math.ceil(mw.n/.9));
console.log('Ordinal reference, ties, symmetric / zero directional effects, validation, and recruitment checks passed.');
